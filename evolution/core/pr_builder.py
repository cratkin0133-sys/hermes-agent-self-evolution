"""Package an evolution result for human review.

Writes evolved files plus a PR-ready summary to the output directory and,
optionally, commits them on a new branch in a *git worktree* of hermes-agent,
leaving the user's checkout untouched. Nothing is pushed: a human reviews,
pushes and opens the PR.
"""

import difflib
import json
import subprocess
from pathlib import Path
from typing import Optional


def unified_diff(old: str, new: str, path: str) -> str:
    return "".join(difflib.unified_diff(
        old.splitlines(keepends=True), new.splitlines(keepends=True),
        fromfile=f"a/{path}", tofile=f"b/{path}",
    ))


def write_review_bundle(
    out_dir: Path,
    title: str,
    summary: str,
    metrics: dict,
    changes: dict[str, tuple[str, str]],
) -> Path:
    """Write PR_BODY.md, metrics.json, changes.diff and evolved file copies.

    ``changes`` maps repo-relative path -> (old_content, new_content).
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    diff = "".join(unified_diff(old, new, rel) for rel, (old, new) in changes.items())
    (out_dir / "changes.diff").write_text(diff)
    (out_dir / "metrics.json").write_text(json.dumps(metrics, indent=2, default=str))
    for rel, (_, new) in changes.items():
        dest = out_dir / "evolved" / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(new)
    rows = "\n".join(f"| {k} | {v} |" for k, v in metrics.items() if not isinstance(v, (dict, list)))
    body = (
        f"# {title}\n\n{summary}\n\n## Metrics\n\n| Metric | Value |\n|---|---|\n{rows}\n\n"
        f"## Files changed\n\n" + "\n".join(f"- `{p}`" for p in changes) +
        "\n\n## Review checklist\n\n- [ ] Evolved text is factually accurate\n"
        "- [ ] No loss of important guidance\n- [ ] hermes-agent test suite passes\n"
        "\n_Generated by hermes-agent-self-evolution. Human review required before merge._\n"
    )
    (out_dir / "PR_BODY.md").write_text(body)
    return out_dir / "PR_BODY.md"


def _git(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True)


def create_branch(
    hermes_repo: Path,
    branch: str,
    files: dict[str, str],
    message: str,
    worktree_dir: Path,
) -> Optional[Path]:
    """Commit ``files`` (rel path -> content) on ``branch`` in a new worktree.

    Returns the worktree path, or None if hermes_repo is not a git repo.
    """
    if _git(hermes_repo, "rev-parse", "--git-dir").returncode != 0:
        return None
    worktree_dir.parent.mkdir(parents=True, exist_ok=True)
    r = _git(hermes_repo, "worktree", "add", "-b", branch, str(worktree_dir), "HEAD")
    if r.returncode != 0:
        raise RuntimeError(f"git worktree add failed: {r.stderr.strip()}")
    for rel, content in files.items():
        (worktree_dir / rel).write_text(content)
    _git(worktree_dir, "add", *files.keys())
    r = _git(worktree_dir, "-c", "user.name=hermes-self-evolution", "-c", "user.email=evolution@localhost",
             "commit", "-q", "-m", message)
    if r.returncode != 0:
        raise RuntimeError(f"git commit failed: {r.stderr.strip() or r.stdout.strip()}")
    return worktree_dir
